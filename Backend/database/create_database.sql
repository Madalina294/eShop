-- =====================================================================
-- eShop - script de creare a bazei de date si a tabelelor (PostgreSQL)
--
-- Rulare (din folderul Backend/database):
--   psql -U postgres -f create_database.sql
--
-- Scriptul poate fi rulat de mai multe ori: baza de date si tabelele
-- sunt create doar daca nu exista deja.
-- =====================================================================

-- 1. Creeaza baza de date "eShop" daca nu exista
--    (CREATE DATABASE nu suporta IF NOT EXISTS, de aceea folosim \gexec)
SELECT 'CREATE DATABASE "eShop" ENCODING ''UTF8'''
WHERE NOT EXISTS (SELECT FROM pg_database WHERE datname = 'eShop')\gexec

-- 2. Conectare la baza de date nou creata
\connect "eShop"

-- 3. Tabele
BEGIN;

CREATE TABLE IF NOT EXISTS users (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    firstname             VARCHAR(255),
    lastname              VARCHAR(255),
    email                 VARCHAR(255),
    phone_number          VARCHAR(255),
    password              VARCHAR(255),
    image_url             VARCHAR(255),
    google_id             VARCHAR(255),
    created_at            TIMESTAMP(6),
    preferred_theme       VARCHAR(255),
    preferred_language    VARCHAR(255),
    mfa_enabled           BOOLEAN NOT NULL DEFAULT FALSE,
    secret                VARCHAR(255),
    reset_password_token  VARCHAR(255),
    reset_password_expiry TIMESTAMP(6),
    role                  VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255),
    description TEXT
);

CREATE TABLE IF NOT EXISTS products (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255),
    price       FLOAT(53) NOT NULL DEFAULT 0,
    image       VARCHAR(255),
    category_id BIGINT NOT NULL,
    color       VARCHAR(255),
    description TEXT,
    dimensions  VARCHAR(255),
    material    VARCHAR(255),
    weight      VARCHAR(255),
    quantity    INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fk_products_category
        FOREIGN KEY (category_id) REFERENCES categories (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS orders (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                  BIGINT NOT NULL,
    status                   VARCHAR(255),
    payment_method           VARCHAR(255),
    shipping_method          VARCHAR(255),
    shipping_address         VARCHAR(255),
    billing_address          VARCHAR(255),
    total_amount             FLOAT(53),
    stripe_payment_intent_id VARCHAR(255),
    order_date               TIMESTAMP(6),
    delivery_date            TIMESTAMP(6),
    created_at               TIMESTAMP(6),
    updated_at               TIMESTAMP(6),
    CONSTRAINT fk_orders_user
        FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE IF NOT EXISTS order_items (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    BIGINT NOT NULL,
    product_id  BIGINT NOT NULL,
    quantity    INTEGER,
    unit_price  FLOAT(53),
    total_price FLOAT(53),
    CONSTRAINT fk_order_items_order
        FOREIGN KEY (order_id) REFERENCES orders (id),
    CONSTRAINT fk_order_items_product
        FOREIGN KEY (product_id) REFERENCES products (id)
);

CREATE TABLE IF NOT EXISTS cart_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    quantity   INTEGER NOT NULL,
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6),
    CONSTRAINT fk_cart_items_user
        FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_cart_items_product
        FOREIGN KEY (product_id) REFERENCES products (id)
);

CREATE TABLE IF NOT EXISTS wishlist_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    added_at   TIMESTAMP(6),
    CONSTRAINT fk_wishlist_items_user
        FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_wishlist_items_product
        FOREIGN KEY (product_id) REFERENCES products (id)
);

CREATE TABLE IF NOT EXISTS activity_logs (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT,
    action_type        VARCHAR(255) NOT NULL,
    action_description TEXT,
    ip_address         VARCHAR(255),
    user_agent         TEXT,
    status             VARCHAR(255) NOT NULL DEFAULT 'SUCCESS',
    metadata           TEXT,
    created_at         TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_activity_logs_user
        FOREIGN KEY (user_id) REFERENCES users (id)
);

COMMIT;
